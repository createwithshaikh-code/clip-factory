"""Describe the sound effects and music in assets/ so Claude can choose them without hearing them.

`./cf assets` writes assets/catalog.md: every file's exact name (what plan.json uses), length,
loudness, how punchy or sustained it is, how bass-heavy or bright it is, and for music a tempo.
Notes you write in assets/sfx/notes.yaml or assets/music/notes.yaml ("vine_boom: after a shocking line")
are added to the catalog and win over the measurements.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

import numpy as np
import yaml

from .config import ASSETS_DIR, AUDIO_EXTS, MUSIC_DIR, SFX_DIR
from .ffmpeg import ffmpeg_bin

RATE = 16000


def _decode(path: Path, seconds: float | None = None) -> np.ndarray:
    cmd = [ffmpeg_bin(), "-hide_banner", "-loglevel", "error", "-i", str(path)]
    if seconds:
        cmd += ["-t", str(seconds)]
    cmd += ["-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"]
    raw = subprocess.run(cmd, capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768.0


def _features(x: np.ndarray) -> dict:
    if len(x) < RATE // 20:
        return {"seconds": round(len(x) / RATE, 2)}
    hop = RATE // 50  # 20 ms
    n = len(x) // hop
    frames = x[: n * hop].reshape(n, hop)
    rms = np.sqrt((frames ** 2).mean(axis=1) + 1e-12)
    db = 20 * np.log10(rms + 1e-9)
    peak_i = int(rms.argmax())
    loud = rms > rms.max() * 0.25
    # spectrum of the loudest 0.5 s
    a = max(0, peak_i * hop - RATE // 4)
    seg = x[a:a + RATE // 2]
    spec = np.abs(np.fft.rfft(seg * np.hanning(len(seg)))) if len(seg) > 64 else np.zeros(2)
    freqs = np.fft.rfftfreq(len(seg), 1 / RATE) if len(seg) > 64 else np.zeros(2)
    centroid = float((spec * freqs).sum() / (spec.sum() + 1e-9))
    low = float(spec[freqs < 200].sum() / (spec.sum() + 1e-9))
    return {
        "seconds": round(len(x) / RATE, 2),
        "loudness_db": round(float(db[loud].mean()) if loud.any() else float(db.mean()), 1),
        "attack_s": round(peak_i * hop / RATE, 2),        # time to the loudest point
        "sustain_s": round(float(loud.sum()) * hop / RATE, 2),  # how long it stays loud
        "brightness_hz": int(centroid),
        "bass_share": round(low, 2),
    }


def _describe_sfx(f: dict) -> str:
    if "loudness_db" not in f:
        return "very short"
    parts = []
    parts.append("hits instantly" if f["attack_s"] < 0.08 else f"builds for {f['attack_s']}s")
    parts.append("short hit" if f["sustain_s"] < 0.4 else ("medium" if f["sustain_s"] < 1.5 else "long/sustained"))
    if f["bass_share"] > 0.45 or f["brightness_hz"] < 500:
        parts.append("deep/bassy (boom, thud)")
    elif f["brightness_hz"] > 2500:
        parts.append("bright/sharp (ding, whoosh, scratch, voice)")
    else:
        parts.append("mid (voice-like or musical)")
    return ", ".join(parts)


def _tempo(x: np.ndarray) -> int | None:
    hop = RATE // 100  # 10 ms
    n = len(x) // hop
    if n < 400:
        return None
    env = np.sqrt((x[: n * hop].reshape(n, hop) ** 2).mean(axis=1))
    onset = np.maximum(0, np.diff(env))
    onset -= onset.mean()
    ac = np.correlate(onset, onset, mode="full")[len(onset) - 1:]
    lo, hi = int(60 / 180 * 100), int(60 / 60 * 100)  # 60-180 BPM
    if hi >= len(ac):
        return None
    lag = lo + int(ac[lo:hi].argmax())
    return int(round(6000 / lag))


def _notes(folder: Path) -> dict:
    p = folder / "notes.yaml"
    if p.exists():
        return yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    return {}


def build_catalog() -> Path:
    lines = [
        "# Asset catalog (generated by `./cf assets`, do not edit; add notes in assets/sfx/notes.yaml)",
        "",
        "Use the **name** column exactly in plan.json. Claude cannot hear these files: the description",
        "is measured from the audio, so also trust the file name and any notes.",
        "",
        "## Sound effects (assets/sfx)",
        "",
        "| name | seconds | loudness dB | character | notes |",
        "|---|---|---|---|---|",
    ]
    sfx_notes = _notes(SFX_DIR)
    sfx_files = sorted(p for p in SFX_DIR.rglob("*") if p.suffix.lower() in AUDIO_EXTS)
    for p in sfx_files:
        try:
            f = _features(_decode(p, 10))
            desc = _describe_sfx(f)
        except Exception as exc:
            f, desc = {"seconds": "?"}, f"could not read ({exc.__class__.__name__})"
        note = str(sfx_notes.get(p.stem, "")).replace("|", "/")
        lines.append(f"| {p.stem} | {f.get('seconds')} | {f.get('loudness_db', '')} | {desc} | {note} |")
    if not sfx_files:
        lines.append("| (none yet) | | | | |")

    lines += ["", "## Music (assets/music/<mood>)", "",
              "| mood folder | file | seconds | tempo BPM | loudness dB | notes |", "|---|---|---|---|---|---|"]
    music_notes = _notes(MUSIC_DIR)
    music_files = sorted(p for p in MUSIC_DIR.rglob("*") if p.suffix.lower() in AUDIO_EXTS)
    for p in music_files:
        mood = p.parent.name if p.parent != MUSIC_DIR else "(no mood folder!)"
        try:
            x = _decode(p, 60)
            f = _features(x)
            bpm = _tempo(x)
            total = _duration(p)
        except Exception as exc:
            f, bpm, total = {}, None, f"? ({exc.__class__.__name__})"
        note = str(music_notes.get(p.stem, "")).replace("|", "/")
        lines.append(f"| {mood} | {p.name} | {total} | {bpm or ''} | {f.get('loudness_db', '')} | {note} |")
    if not music_files:
        lines.append("| (none yet) | | | | | |")
    loose = [p for p in music_files if p.parent == MUSIC_DIR]
    if loose:
        lines += ["", f"**{len(loose)} music file(s) are not in a mood folder.** They are only used when the clip's "
                  "mood folder is empty. Move them into hype/ funny/ sad/ emotional/ chill/ suspense/."]

    fonts = sorted(p.name for p in (ASSETS_DIR / "fonts").glob("*") if p.suffix.lower() in (".ttf", ".otf"))
    lines += ["", "## Fonts (assets/fonts)", "", ", ".join(fonts) if fonts else "(none: the system bold font is used)",
              "", "Set `captions.font: <file name>` in a channel YAML to pick one; with no setting the first one is used."]

    out = ASSETS_DIR / "catalog.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(sfx_files)} sfx, {len(music_files)} music, {len(fonts)} fonts -> {out}")
    return out


def _duration(path: Path) -> float:
    r = subprocess.run([ffmpeg_bin(), "-hide_banner", "-i", str(path)], capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    for line in r.stderr.splitlines():
        line = line.strip()
        if line.startswith("Duration:"):
            h, m, s = line.split()[1].rstrip(",").split(":")
            return round(int(h) * 3600 + int(m) * 60 + float(s), 1)
    return 0.0
